for (nm in names(presets)) {
  run <- run_lake(presets[[nm]], params)
  cat("\n---", nm, "---\n")
  print(result_table(run))
  print(round(unlist(run$metrics), 4))
}

cat("\nBuilding approximate playable frontier grid...\n")
grid <- frontier_grid(params, n_grid = 5000, seed = 42)
cat("Number of approximate frontier points:", sum(grid$is_frontier_point), "\n")

# Score a preset against the approximate frontier.
score <- score_offer_against_grid(presets$highest_raw_outcome, params, grid = grid)
