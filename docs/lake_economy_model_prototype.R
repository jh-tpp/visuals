print(round(c(
  ce_loss_vs_equal = score$ce_loss_vs_equal,
  blended_gain_vs_equal = score$blended_gain_vs_equal,
  best_gain_at_no_more_loss = score$best_gain_at_no_more_loss,
  frontier_recovery = score$frontier_recovery
), 4))

